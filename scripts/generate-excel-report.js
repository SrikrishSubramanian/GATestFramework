const ExcelJS = require('exceljs');
const fs = require('fs');
const path = require('path');

/**
 * Generate Excel report containing only FAILED test cases
 * Reads from playwright test results and creates a formatted Excel file
 * in the restricted .claude/excel/ directory
 */

async function generateExcelReport() {
  try {
    console.log('\n📊 Starting Excel Report Generation...');

    // Find the most recent test results file
    const reportDirPattern = 'playwright-report';
    const reportDir = path.join(__dirname, '..', reportDirPattern);

    if (!fs.existsSync(reportDir)) {
      console.log('⚠️  No test results found - Excel report not generated');
      return;
    }

    // Find the latest results.json file
    let latestResultsPath = null;
    let latestModified = 0;

    function findLatestResults(dir) {
      const items = fs.readdirSync(dir);
      items.forEach(item => {
        const itemPath = path.join(dir, item);
        const stat = fs.statSync(itemPath);

        if (stat.isDirectory()) {
          findLatestResults(itemPath);
        } else if (item === 'results.json') {
          const modified = stat.mtimeMs;
          if (modified > latestModified) {
            latestModified = modified;
            latestResultsPath = itemPath;
          }
        }
      });
    }

    findLatestResults(reportDir);

    if (!latestResultsPath) {
      console.log('⚠️  No test results.json found - Excel report not generated');
      return;
    }

    console.log(`📁 Found test results: ${latestResultsPath}`);

    // Read test results
    const resultsContent = fs.readFileSync(latestResultsPath, 'utf-8');
    const results = JSON.parse(resultsContent);

    // Filter for failed tests only
    const failedTests = [];

    if (results.suites && Array.isArray(results.suites)) {
      results.suites.forEach(suite => {
        if (suite.tests && Array.isArray(suite.tests)) {
          suite.tests.forEach(test => {
            if (test.status === 'failed') {
              failedTests.push({
                title: test.title,
                suite: suite.title || 'Unknown Suite',
                status: test.status,
                error: test.error?.message || test.error?.stack || 'Unknown error',
                duration: test.duration || 0,
                file: suite.file || 'Unknown file',
                retries: test.retries || 0,
                timeout: test.timeout || false,
              });
            }
          });
        }
      });
    }

    // If no failed tests, create a summary file only
    if (failedTests.length === 0) {
      console.log('✅ All tests passed! No failed cases to report.');

      const excelDir = path.join(__dirname, '..', '.claude', 'excel');
      if (!fs.existsSync(excelDir)) {
        fs.mkdirSync(excelDir, { recursive: true });
      }

      // Create a "All Tests Passed" workbook
      const workbook = new ExcelJS.Workbook();
      const worksheet = workbook.addWorksheet('Summary');

      worksheet.columns = [
        { header: 'Status', key: 'status', width: 25 },
        { header: 'Value', key: 'value', width: 40 },
      ];

      worksheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
      worksheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF28a745' } };

      worksheet.addRow({ status: 'Test Result', value: '✅ ALL TESTS PASSED' });
      worksheet.addRow({ status: 'Total Tests', value: results.stats?.expected || 0 });
      worksheet.addRow({ status: 'Failed Tests', value: 0 });
      worksheet.addRow({ status: 'Report Generated', value: new Date().toLocaleString() });
      worksheet.addRow({ status: 'Generated By', value: 'PuneethAM' });

      const summaryPath = path.join(excelDir, `all-tests-passed-${getDateStamp()}.xlsx`);
      await workbook.xlsx.writeFile(summaryPath);

      console.log(`✅ Excel report created: ${summaryPath}`);
      console.log(`   Status: All tests passed`);
      console.log(`   Access: RESTRICTED (User only)\n`);
      return;
    }

    // Create Excel file with failed tests
    const excelDir = path.join(__dirname, '..', '.claude', 'excel');
    if (!fs.existsSync(excelDir)) {
      fs.mkdirSync(excelDir, { recursive: true });
    }

    const workbook = new ExcelJS.Workbook();

    // Sheet 1: Failed Tests
    const worksheet = workbook.addWorksheet('Failed Tests');

    worksheet.columns = [
      { header: 'Test Name', key: 'title', width: 40 },
      { header: 'Suite', key: 'suite', width: 30 },
      { header: 'Status', key: 'status', width: 12 },
      { header: 'Error Message', key: 'error', width: 60 },
      { header: 'Duration (ms)', key: 'duration', width: 15 },
      { header: 'File', key: 'file', width: 35 },
      { header: 'Retries', key: 'retries', width: 10 },
    ];

    // Style header row
    worksheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
    worksheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFDC3545' } };
    worksheet.getRow(1).alignment = { horizontal: 'center', vertical: 'center', wrapText: true };

    // Add failed tests
    failedTests.forEach((test, index) => {
      const row = worksheet.addRow({
        title: test.title,
        suite: test.suite,
        status: test.status,
        error: test.error,
        duration: test.duration,
        file: test.file,
        retries: test.retries,
      });

      // Style failed test rows
      row.getCell('status').fill = {
        type: 'pattern',
        pattern: 'solid',
        fgColor: { argb: 'FFFF6B6B' }
      };

      // Alternate row colors for readability
      if (index % 2 === 0) {
        row.fill = {
          type: 'pattern',
          pattern: 'solid',
          fgColor: { argb: 'FFF8F9FA' }
        };
      }

      // Wrap text for error column
      row.getCell('error').alignment = { wrapText: true, vertical: 'top' };
    });

    // Auto-fit columns
    worksheet.columns.forEach(column => {
      let maxLength = column.header ? column.header.length : 0;
      column.width = Math.min(maxLength + 2, 60);
    });

    // Sheet 2: Summary
    const summarySheet = workbook.addWorksheet('Summary');

    summarySheet.columns = [
      { header: 'Metric', key: 'metric', width: 30 },
      { header: 'Value', key: 'value', width: 40 },
    ];

    summarySheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
    summarySheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FF0066cc' } };

    const summaryRows = [
      { metric: 'Total Tests Run', value: results.stats?.expected || 0 },
      { metric: 'Total Failed Tests', value: failedTests.length },
      { metric: 'Failed Test Percentage', value: `${((failedTests.length / (results.stats?.expected || 1)) * 100).toFixed(2)}%` },
      { metric: 'Report Generated', value: new Date().toLocaleString() },
      { metric: 'Generated By', value: 'PuneethAM' },
      { metric: 'Test Environment', value: process.env.env || 'local' },
    ];

    summaryRows.forEach(row => {
      summarySheet.addRow(row);
    });

    // Sheet 3: Failed Tests by Suite
    const failedBySuite = {};
    failedTests.forEach(test => {
      if (!failedBySuite[test.suite]) {
        failedBySuite[test.suite] = 0;
      }
      failedBySuite[test.suite]++;
    });

    const suiteSheet = workbook.addWorksheet('By Suite');
    suiteSheet.columns = [
      { header: 'Suite Name', key: 'suite', width: 40 },
      { header: 'Failed Tests Count', key: 'count', width: 20 },
    ];

    suiteSheet.getRow(1).font = { bold: true, color: { argb: 'FFFFFFFF' } };
    suiteSheet.getRow(1).fill = { type: 'pattern', pattern: 'solid', fgColor: { argb: 'FFF59E0B' } };

    Object.entries(failedBySuite).forEach(([suite, count]) => {
      suiteSheet.addRow({ suite, count });
    });

    // Save workbook
    const dateStamp = getDateStamp();
    const excelPath = path.join(excelDir, `failed-tests-${dateStamp}.xlsx`);

    await workbook.xlsx.writeFile(excelPath);

    console.log(`\n✅ Excel Report Generated Successfully!`);
    console.log(`📁 Location: ${excelPath}`);
    console.log(`🔒 Access: RESTRICTED (User only)`);
    console.log(`📊 Failed Tests: ${failedTests.length}`);
    console.log(`📋 Sheets: Failed Tests, Summary, By Suite`);
    console.log('');

  } catch (error) {
    console.error('\n❌ Error generating Excel report:', error.message);
    console.error(error.stack);
    process.exit(1);
  }
}

/**
 * Generate date stamp for file naming (YYYY-MM-DD-HH-MM-SS)
 */
function getDateStamp() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  const hours = String(now.getHours()).padStart(2, '0');
  const minutes = String(now.getMinutes()).padStart(2, '0');
  const seconds = String(now.getSeconds()).padStart(2, '0');

  return `${year}-${month}-${day}-${hours}-${minutes}-${seconds}`;
}

// Run the function
generateExcelReport().catch(error => {
  console.error('Fatal error:', error);
  process.exit(1);
});
